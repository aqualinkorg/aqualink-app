import { existsSync, writeFileSync } from 'fs';
import { resolve } from 'path';

const envPath = process.env.DOTENV_CONFIG_PATH;
const projectId = process.env.FIREBASE_PROJECT_ID;

if (!envPath || !projectId) {
  // eslint-disable-next-line no-console
  console.error(
    'DOTENV_CONFIG_PATH and FIREBASE_PROJECT_ID are required. Use one of:\n' +
      '  yarn config:cloud-functions:prod\n' +
      '  yarn config:cloud-functions:staging\n' +
      '  yarn config:cloud-functions:programize',
  );
  process.exit(1);
}

const resolvedEnvPath = resolve(process.cwd(), envPath);
if (!existsSync(resolvedEnvPath)) {
  // eslint-disable-next-line no-console
  console.error(`Env file not found: ${resolvedEnvPath}`);
  process.exit(1);
}

try {
  // eslint-disable-next-line import/no-extraneous-dependencies, global-require
  require('dotenv').config({ path: resolvedEnvPath, quiet: true });
} catch {
  // Pass
}

// 2nd gen functions read process.env. These names match the API .env files.
// Firebase CLI loads `.env.<projectId>` from the functions source (repo root)
// at deploy time. `functions.config()` / Runtime Config is 1st gen only.
const envKeys = [
  'SLACK_BOT_TOKEN',
  'SLACK_BOT_CHANNEL',
  'SOFAR_API_TOKEN',
  'OPEN_METEO_API_KEY',
  'OPEN_METEO_ENABLED',
  'FRONT_END_BASE_URL',
  'BACKEND_BASE_URL',
  'FIREBASE_API_KEY',
  'DATABASE_URL',
] as const;

const requiredKeys = ['DATABASE_URL', 'SOFAR_API_TOKEN', 'BACKEND_BASE_URL'];

const missing = requiredKeys.filter((key) => {
  const value = process.env[key];
  return !value || value === 'undefined';
});

if (missing.length > 0) {
  // eslint-disable-next-line no-console
  console.error(
    `Missing required env vars in ${resolvedEnvPath}: ${missing.join(', ')}`,
  );
  process.exit(1);
}

function encodeDotenvValue(value: string): string {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/"/g, '\\"')
    .replace(/\$/g, '\\$');
  return `"${escaped}"`;
}

const defined = envKeys.filter((key) => {
  const value = process.env[key];
  return value !== undefined && value !== 'undefined' && value !== '';
});

const outputPath = resolve(process.cwd(), `../../.env.${projectId}`);
const body = [
  '# Generated by packages/api/functionsConfig.ts. Do not commit.',
  '# Loaded by the Firebase CLI when deploying 2nd gen Cloud Functions.',
  ...defined.map((key) => `${key}=${encodeDotenvValue(process.env[key]!)}`),
  '',
].join('\n');

writeFileSync(outputPath, body);

const databaseHost = process.env.DATABASE_URL!.split('@')[1] ?? '(unknown)';
// stderr so secrets are not printed
// eslint-disable-next-line no-console
console.error(`Loading Firebase functions env from ${resolvedEnvPath}`);
// eslint-disable-next-line no-console
console.error(`database host → ${databaseHost}`);
// eslint-disable-next-line no-console
console.error(
  `Wrote ${outputPath} (${defined.length} vars: ${defined.join(', ')})`,
);
